# One-time conversion script: turns the Zig curve catalog
# (curve_data_random.zig + curve_paths.bin) from the HilbertCurveCompact
# repo into committed Julia-package data:
#
#   data/curve_paths.bin          byte-for-byte copy of the u16 path blob
#   src/curve_catalog_data.jl     generated Julia source (Gray codes + path index)
#
# Usage:
#   julia --project=gen gen/convert_curve_data.jl [/path/to/HilbertCurveCompact]
#
# The script is committed for reproducibility. Re-running it on the same inputs
# reproduces src/curve_catalog_data.jl byte-identically.

using SHA

const DEFAULT_ZIG_REPO = "/Users/adolgert/dev/HilbertCurveCompact"

const REPO_ROOT = normpath(joinpath(@__DIR__, ".."))

"""
    parse_gray_codes(text) -> Vector{NamedTuple}

Parse the `random_gray` array out of the machine-generated Zig source. Each
entry looks like:

    .{ .k = 3, .gi = 0, .gray = &.{ 0, 4, 6, 2, 3, 7, 5, 1 } },

Returns named tuples `(k, gi, gray)` in file order.
"""
function parse_gray_codes(text::AbstractString)
    entries = NamedTuple[]
    re = r"\.\{\s*\.k\s*=\s*(\d+)\s*,\s*\.gi\s*=\s*(\d+)\s*,\s*\.gray\s*=\s*&\.\{([^}]*)\}\s*\}"
    for m in eachmatch(re, text)
        k = parse(Int, m.captures[1])
        gi = parse(Int, m.captures[2])
        gray = UInt16[parse(UInt16, strip(s)) for s in split(m.captures[3], ",") if !isempty(strip(s))]
        push!(entries, (k = k, gi = gi, gray = gray))
    end
    return entries
end

"""
    parse_path_index(text) -> Vector{NamedTuple}

Parse the `path_index` array out of the machine-generated Zig source. Each
entry looks like:

    .{ .k = 3, .gi = 0, .pi = 0, .off = 0, .len = 8 },

Returns named tuples `(k, gi, pi, off, len)` in file order.
"""
function parse_path_index(text::AbstractString)
    entries = NamedTuple[]
    re = r"\.\{\s*\.k\s*=\s*(\d+)\s*,\s*\.gi\s*=\s*(\d+)\s*,\s*\.pi\s*=\s*(\d+)\s*,\s*\.off\s*=\s*(\d+)\s*,\s*\.len\s*=\s*(\d+)\s*\}"
    for m in eachmatch(re, text)
        push!(entries, (
            k = parse(Int, m.captures[1]),
            gi = parse(Int, m.captures[2]),
            pi = parse(Int, m.captures[3]),
            off = parse(UInt32, m.captures[4]),
            len = parse(UInt32, m.captures[5]),
        ))
    end
    return entries
end

"""
    validate_gray_code(k, gray)

Throw an error unless `gray` is a valid cyclic Gray code of level width `k`:
length `2^k`, starts at 0, all entries unique and `< 2^k`, consecutive entries
(including the wraparound last -> first) differ in exactly one bit.
"""
function validate_gray_code(k::Integer, gray::AbstractVector{UInt16})
    n = 1 << k
    length(gray) == n || error("gray code k=$k has length $(length(gray)), expected $n")
    gray[1] == 0 || error("gray code k=$k does not start at 0 (starts at $(gray[1]))")
    length(Set(gray)) == n || error("gray code k=$k has duplicate entries")
    for g in gray
        g < n || error("gray code k=$k has entry $g >= $n")
    end
    for i in 1:n
        a = gray[i]
        b = gray[i == n ? 1 : i + 1]
        count_ones(a ⊻ b) == 1 || error("gray code k=$k step $i (=$a) -> next (=$b) is not Hamming-1")
    end
    return nothing
end

function main(args)
    zig_repo = isempty(args) ? DEFAULT_ZIG_REPO : args[1]
    zig_src = joinpath(zig_repo, "src", "curve_data_random.zig")
    zig_blob = joinpath(zig_repo, "src", "curve_paths.bin")

    isfile(zig_src) || error("cannot find $zig_src")
    isfile(zig_blob) || error("cannot find $zig_blob")

    text = read(zig_src, String)
    grays = parse_gray_codes(text)
    paths = parse_path_index(text)

    println("Parsed $(length(grays)) Gray codes and $(length(paths)) path refs.")

    # Validate every Gray code before emitting anything.
    for g in grays
        validate_gray_code(g.k, g.gray)
    end
    println("All Gray codes validated.")

    # Copy the blob byte-for-byte and record its digest.
    blob_bytes = read(zig_blob)
    data_dir = joinpath(REPO_ROOT, "data")
    mkpath(data_dir)
    out_blob = joinpath(data_dir, "curve_paths.bin")
    write(out_blob, blob_bytes)
    sha = bytes2hex(SHA.sha256(blob_bytes))
    nbytes = length(blob_bytes)
    println("Copied blob: $nbytes bytes, sha256=$sha")

    # Emit generated Julia source with a stable ordering (file order is already
    # sorted by (k, gi[, pi]); we keep it as-is so re-running is reproducible).
    out_src = joinpath(REPO_ROOT, "src", "curve_catalog_data.jl")
    open(out_src, "w") do io
        println(io, "# GENERATED by gen/convert_curve_data.jl — do not edit.")
        println(io, "#")
        println(io, "# Random-family cyclic Gray codes and the child_entry path index for the")
        println(io, "# Hilbert curve catalog, converted from the HilbertCurveCompact Zig repo.")
        println(io, "# The path data itself lives in data/curve_paths.bin (little-endian u16).")
        println(io)
        println(io, "const RANDOM_GRAY = [")
        for g in grays
            joined = join(string.(g.gray), ", ")
            println(io, "    (k = $(g.k), gi = $(g.gi), gray = UInt16[$joined]),")
        end
        println(io, "]")
        println(io)
        println(io, "const PATH_INDEX = [")
        for p in paths
            off = string("0x", string(p.off, base = 16, pad = 8))
            len = string("0x", string(p.len, base = 16, pad = 8))
            println(io, "    (k = $(p.k), gi = $(p.gi), pi = $(p.pi), off = $off, len = $len),")
        end
        println(io, "]")
        println(io)
        println(io, "const CURVE_PATHS_SHA256 = \"$sha\"")
        println(io, "const CURVE_PATHS_BYTES = $nbytes")
    end
    println("Wrote $out_src")
end

main(ARGS)
